import { mkdir } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

const frames = 'output/playwright/account-identity'
for (const theme of ['light', 'dark'] as const) for (const width of [1440, 720]) {
  test(`account identity explicit saves, cancellation and account switch ${width} ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 800 })
    await page.goto(`/preview.html?desk-account=settings&theme=${theme}`)
    const settings = page.getByRole('region', { name: 'Settings', exact: true, includeHidden: true })
    await expect(settings).toContainText('Jane at work')
    await expect(settings).toContainText('jane@example.com')
    await expect(settings).not.toContainText('Local profile')
    await mkdir(frames, { recursive: true })
    await page.screenshot({ path: `${frames}/after-account-${width}-${theme}.png` })
    const edit = settings.getByRole('button', { name: 'Edit', exact: true })
    await edit.focus(); await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name: 'Edit display name' })
    const field = dialog.getByRole('textbox', { name: 'Display name', exact: true })
    await expect(field).toBeFocused(); await field.fill('Temporary name')
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(edit).toBeFocused(); await expect(settings).toContainText('Jane at work')
    await edit.click(); await field.fill('Jane in the studio'); await dialog.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(settings).toContainText('Jane in the studio')
    await edit.click(); await field.fill(''); await field.press('Enter')
    await expect(settings).toContainText('Jane Doe')
    await edit.click(); await field.fill('Stale draft')
    await page.evaluate(() => { const store = (window as any).__hdIdentity; const status = store.getSnapshot().harnessDeskAccount; store.transport.handlers.onNotification({ method: 'account/changed', params: { status: { ...status, account: { ...status.account, id: 'other', nickname: 'Demo Person', email: 'demo@example.com' } } } }) })
    await expect(dialog).toHaveCount(0); await expect(settings).toContainText('Demo Person')
    await expect(settings).not.toContainText('Stale draft')
    await page.goto(`/preview.html?desk-account=settings-save-failed&theme=${theme}`)
    await settings.getByRole('button', { name: 'Edit', exact: true }).click(); await field.fill('Retained draft')
    await dialog.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('Could not save')
    await expect(field).toHaveValue('Retained draft'); await expect(settings).toContainText('Jane at work')
    await page.screenshot({ path: `${frames}/after-account-failed-${width}-${theme}.png` })
    const bounds = await dialog.boundingBox(); expect(bounds!.x).toBeGreaterThanOrEqual(0); expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
  })
  test(`signed-out desk and independent app icon ${width} ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 800 })
    await page.goto(`/preview.html?desk-account=signed-out&account-section=general&theme=${theme}`)
    const settings = page.getByRole('region', { name: 'Settings', exact: true, includeHidden: true })
    await expect(settings.getByRole('heading', { name: 'This desk', exact: true })).toBeVisible()
    await expect(settings).toContainText('Work Mac')
    await page.screenshot({ path: `${frames}/after-general-${width}-${theme}.png` })
    await settings.getByRole('button', { name: 'Rename', exact: true }).click()
    const rename = page.getByRole('dialog', { name: 'Rename this desk' })
    await rename.getByRole('textbox', { name: 'Desk name' }).fill('Travel Mac')
    await rename.getByRole('button', { name: 'Rename', exact: true }).click()
    await expect(settings).toContainText('Travel Mac')
    await page.goto(`/preview.html?desk-account=settings&account-section=appearance&theme=${theme}`)
    const change = settings.getByRole('button', { name: 'Change…', exact: true })
    await expect(change).toBeVisible()
    await expect(page.locator('[data-slot="picture-choices"]')).toHaveCount(0)
    await page.screenshot({ path: `${frames}/after-appearance-${width}-${theme}.png` })
    await page.evaluate(() => Object.assign((window as any).__hdIdentity.getSnapshot(), { appIcon: 'future-icon' }))
    await change.focus(); await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name: 'App icon', exact: true })
    const group = dialog.getByRole('radiogroup', { name: 'Picture', exact: true })
    await expect(group.getByRole('radio', { checked: true })).toHaveCount(0)
    const first = group.getByRole('radio', { name: 'Default', exact: true })
    await first.focus(); await page.keyboard.press('ArrowLeft')
    expect(await page.evaluate(() => (window as any).__hdIdentity.getSnapshot().appIcon)).toBe('future-icon')
    await page.keyboard.press('ArrowRight'); await expect(group.getByRole('radio', { name: 'Paper', exact: true })).toBeChecked()
    await page.keyboard.press('ArrowDown'); await expect(group.locator('[role="radio"][aria-checked="true"]')).toBeFocused()
    const wizard = group.getByRole('radio', { name: 'Wizard', exact: true })
    const resting = await wizard.locator(':scope > *').evaluate(node => getComputedStyle(node).transform)
    await wizard.hover(); await expect.poll(() => wizard.locator(':scope > *').evaluate(node => getComputedStyle(node).transform)).not.toBe(resting)
    await expect(wizard).toHaveAttribute('title', /Wizard — /)
    await wizard.click(); await expect(wizard).toBeChecked()
    await expect(group.locator('[role="radio"][tabindex="0"]')).toHaveCount(1)
    await page.screenshot({ path: `${frames}/after-icon-picker-${width}-${theme}.png` })
    expect(await group.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    const box = await dialog.boundingBox(); expect(box!.x).toBeGreaterThanOrEqual(0); expect(box!.x + box!.width).toBeLessThanOrEqual(width)
    await dialog.getByRole('button', { name: 'Restore default', exact: true }).click(); await expect(first).toBeChecked()
    await dialog.getByRole('button', { name: 'Done', exact: true }).click(); await expect(change).toBeFocused()
    expect(await page.evaluate(() => (window as any).__hdIdentity.getSnapshot().appIcon)).toBeNull()
  })
}
