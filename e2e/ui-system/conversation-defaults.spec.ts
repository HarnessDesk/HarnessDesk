import { expect, test } from '@playwright/test'
import { openFrame } from './frame-contract-helpers'

for (const theme of ['light', 'dark'] as const) {
  test(`General new-conversation defaults in ${theme}`, async ({ page }) => {
    await openFrame(page, 'conversation-defaults=1', theme)
    await page.setViewportSize({ width: 1440, height: 1100 })
    const model = page.getByTitle('Default model', { exact: true })
    const permission = page.getByTitle('Default permission level', { exact: true })
    await expect(model).toHaveText('Recommended')
    await expect(permission).toHaveText('Recommended')
    await page.screenshot({ path: `/tmp/hdv-defaults-d2/general-after-${theme}.png` })
    await permission.click()
    await expect(page.getByRole('menuitemradio', { name: 'Workspace write', exact: true })).toBeVisible()
    await page.getByRole('menuitemradio', { name: 'Full access', exact: true }).click()
    await expect(permission).toHaveText('Full access')
    await model.click()
    await page.getByRole('menuitemradio', { name: 'Large', exact: true }).click()
    await expect(model).toHaveText('Large')
    const runtime = page.getByTitle('Default runtime', { exact: true })
    const original = await runtime.textContent()
    await runtime.click()
    const alternative = page.getByRole('menuitemradio').filter({ hasNotText: original! }).first()
    const alternateName = await alternative.textContent()
    await alternative.click()
    await expect(runtime).toHaveText(alternateName!)
    await expect(model).toHaveText('Recommended')
    await runtime.click()
    await page.getByRole('menuitemradio', { name: original!, exact: true }).click()
    await expect(model).toHaveText('Large')
    await expect(permission).toHaveText('Full access')
    await model.click()
    await page.getByRole('menuitemradio', { name: 'Recommended', exact: true }).click()
    await expect(model).toHaveText('Recommended')
    await expect(page.getByText('Your data', { exact: true })).toBeVisible()
    await expect(page.getByText('Backup', { exact: true })).toBeVisible()
  })
}
