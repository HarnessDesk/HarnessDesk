import { expect, test } from '@playwright/test'
import { openFrame } from './frame-contract-helpers'

for (const theme of ['light', 'dark'] as const) test(`Review, transcript lines and dirty popout keep one owning document in ${theme}`, async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await openFrame(page, 'frame-wall=conversation&frame-editor=entry', theme, 1440)
  const right = page.locator('[data-frame-region="right"]'), main = page.locator('[data-slot="editor-main"]')
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(main).toBeVisible()
  await expect(main.getByRole('radio', { name: /^Changes/ })).toBeChecked()
  await expect(page.getByRole('radio', { name: /^Changed/ })).toBeChecked()
  await page.getByRole('button', { name: 'Conversation mode', exact: true }).click()
  await page.getByRole('link', { name: 'README.md:3', exact: true }).click()
  await expect(main.getByRole('radio', { name: 'Source', exact: true })).toBeChecked()
  await expect(main.locator('.cm-linkedLine')).toHaveText('Read the checkout notes before editing.')
  await expect(main.locator('.cm-activeLine')).toHaveText('Read the checkout notes before editing.')
  await page.screenshot({ path: testInfo.outputPath(`entry-line-${theme}.png`) })
  // A row opens the ordinary retained file tool. Its editor seeds the main draft.
  await page.getByRole('button', { name: 'Conversation mode', exact: true }).click()
  await page.getByTitle('Open app/checkout.ts', { exact: true }).click()
  const panelEditor = right.locator('.cm-content')
  await expect(panelEditor).toBeVisible()
  await panelEditor.focus(); await page.keyboard.press('Meta+End'); await page.keyboard.insertText('// panel draft\n')
  await right.getByRole('button', { name: 'Pop out to Editor mode', exact: true }).click()
  await expect(main.locator('.cm-content')).toContainText('// panel draft')
  await expect(main.getByRole('tab', { name: 'checkout.ts, unsaved', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath(`entry-popout-${theme}.png`) })
  await main.getByRole('button', { name: 'Unsaved · Save ⌘S', exact: true }).click()
  await expect(main.getByRole('button', { name: 'Unsaved · Save ⌘S', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Conversation mode', exact: true }).click()
  await page.getByTitle('Open app/checkout.ts', { exact: true }).click()
  await expect(panelEditor).toContainText('// panel draft')
  await expect(right.getByRole('button', { name: 'Unsaved · Save ⌘S', exact: true })).toHaveCount(0)
  expect(errors).toEqual([])
})
