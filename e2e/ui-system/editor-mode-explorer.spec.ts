import { expect, test, type Page } from '@playwright/test'
import { openFrame } from './frame-contract-helpers'
import { applyLeftColumnActions } from './left-column-actions'

const metadata = (page: Page) => page.evaluate(() => (window as Window & { __hdFrameWall: { editorState: () => readonly { state: { active: string | null; preview: string | null; filter: string | null } }[] } }).__hdFrameWall.editorState()[0]?.state)
for (const theme of ['light', 'dark'] as const) {
  for (const width of [1440, 720]) test(`Explorer follows a worktree subfolder and keeps the column anatomy at ${width} in ${theme}`, async ({ page }, testInfo) => {
    const exceptions: string[] = []
    page.on('pageerror', error => exceptions.push(error.message))
    await openFrame(page, 'frame-wall=conversation&frame-explorer=git', theme, width)
    await applyLeftColumnActions(page, { leftOpen: true, leftWidth: width === 720 ? 200 : 256 })
    const column = page.locator('[data-left-column]:visible'), top = column.locator('[data-left-top]')
    await top.getByRole('button', { name: 'Editor mode', exact: true }).click()
    await expect(column.locator('[data-explorer-head]')).toContainText('Changed 4')
    await expect(column.locator('[data-explorer-head] [title]')).toHaveAttribute('title', '/work/storefront-branch/src')
    await expect(column.getByRole('navigation', { name: 'Workspace actions' })).toBeHidden()
    await expect(column.locator('[data-left-seat]')).toBeVisible()
    await expect(column.getByRole('button', { name: 'outside.ts', exact: true })).toHaveCount(0)
    const app = column.getByRole('button', { name: 'app', exact: true })
    await expect(app).toHaveAttribute('aria-expanded', 'false')
    await app.click()
    await expect(app).toHaveAttribute('aria-expanded', 'true')
    const file = column.getByRole('button', { name: 'checkout.ts', exact: true })
    await expect(file).toBeVisible()
    await expect(file.locator('..')).toHaveAttribute('data-letter', 'M')
    await file.click()
    await expect.poll(() => metadata(page)).toMatchObject({ active: '/work/storefront-branch/src/app/checkout.ts', preview: '/work/storefront-branch/src/app/checkout.ts', filter: null })
    await file.dblclick()
    await expect.poll(() => metadata(page)).toMatchObject({ preview: null })
    const directory = column.getByRole('button', { name: 'newdir', exact: true })
    await directory.click()
    await expect.poll(() => metadata(page)).toMatchObject({ active: '/work/storefront-branch/src/app/checkout.ts' })
    await expect(column.getByRole('button', { name: 'draft.md', exact: true })).toBeVisible()
    await column.getByRole('radio', { name: 'All', exact: true }).click()
    await expect(column.getByRole('button', { name: 'unchanged.ts', exact: true })).toBeVisible()
    const geometry = await column.evaluate(node => [...node.querySelectorAll<HTMLElement>('[data-left-tree]')].map(row => ({ height: row.getBoundingClientRect().height, label: row.querySelector('[data-slot="sidebar-menu-label-content"]')!.getBoundingClientRect(), trailing: row.querySelector('[data-left-trailing]')!.getBoundingClientRect() })).map(row => ({ height: row.height, labelRight: row.label.right, trailLeft: row.trailing.left })))
    expect(new Set(geometry.map(row => row.height)).size).toBe(1)
    expect(geometry.every(row => row.labelRight <= row.trailLeft + 0.5)).toBe(true)
    const foot = column.getByRole('button', { name: 'Go to file', exact: true })
    const footInk = await foot.evaluate(node => {
      const probe = document.createElement('span')
      probe.style.backgroundColor = 'var(--hd-input)'; probe.style.border = 'var(--hd-border-width) solid var(--hd-border)'
      node.appendChild(probe)
      const actual = getComputedStyle(node), expected = getComputedStyle(probe)
      const colors = { fill: actual.backgroundColor, edge: actual.borderColor, expectedFill: expected.backgroundColor, expectedEdge: expected.borderColor }
      probe.remove(); return colors
    })
    expect(footInk.fill).toBe(footInk.expectedFill)
    expect(footInk.edge).toBe(footInk.expectedEdge)
    await foot.click()
    const dialog = page.getByRole('dialog', { name: 'Go to file', exact: true })
    await dialog.getByRole('searchbox', { name: 'Find a file', exact: true }).fill('README')
    await dialog.getByRole('button', { name: 'README.md', exact: true }).click()
    await expect(dialog).toBeHidden()
    await expect.poll(() => metadata(page)).toMatchObject({ active: '/work/storefront-branch/src/README.md', preview: null, filter: 'all' })
    await page.keyboard.press('Meta+p')
    await expect(dialog).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(dialog).toBeHidden()
    await page.screenshot({ path: testInfo.outputPath(`explorer-${theme}-${width}.png`) })
    // Settings replaces the middle, then Back restores Editor and its explicit filter.
    await column.locator('[data-left-seat]').getByRole('button', { name: 'Settings', exact: true }).click()
    await expect(column.locator('[data-explorer-head]')).toHaveCount(0)
    await page.keyboard.press('Meta+[')
    await expect(page.locator('[data-page-destination="settings"]:visible')).toHaveCount(0)
    await applyLeftColumnActions(page, { leftOpen: true })
    await expect(top.getByRole('button', { name: 'Editor mode', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(column.getByRole('button', { name: 'unchanged.ts', exact: true })).toBeVisible()
    await expect.poll(() => metadata(page)).toMatchObject({ filter: 'all' })
    expect(exceptions).toEqual([])
  })
  test(`non-Git Explorer offers All files with no filter or letters in ${theme}`, async ({ page }) => {
    await openFrame(page, 'frame-wall=conversation&frame-explorer=plain', theme)
    const column = page.locator('[data-left-column]:visible')
    await column.getByRole('button', { name: 'Editor mode', exact: true }).click()
    await expect(column.getByRole('button', { name: 'unchanged.ts', exact: true })).toBeVisible()
    await expect(column.getByRole('radiogroup', { name: 'Explorer filter', exact: true })).toHaveCount(0)
    await expect(column.locator('[data-left-tree][data-letter]')).toHaveCount(0)
  })
}
