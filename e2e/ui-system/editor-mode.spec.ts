import { expect, test, type Page } from '@playwright/test'
import { openFrame } from './frame-contract-helpers'

const showEditorAtNarrowWidth = async (page: Page, width: number) => {
  if (width >= 1000) return
  const drawer = page.getByRole('dialog', { name: 'Sidebar', exact: true })
  if (await drawer.isVisible()) await drawer.getByRole('button', { name: 'Hide sidebar', exact: true }).click()
}

for (const theme of ['light', 'dark'] as const) {
  test(`editor fixture opens four changed files and one retained dirty tab in ${theme}`, async ({ page }) => {
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
    await openFrame(page, 'frame-wall=conversation&frame-editor-mode=source', theme)
    const main = page.locator('[data-slot="editor-main"]')
    await expect(main).toBeVisible()
    await expect(page.getByRole('radio', { name: 'Changed 4', exact: true })).toBeChecked()
    await expect(main.getByRole('tab')).toHaveCount(2)
    await expect(main.locator('[data-slot="file-tab-unsaved"]')).toHaveCount(1)
    await expect(main.locator('.cm-content')).toContainText('retryPayment')
    const tools = page.locator('[data-work-tool]')
    await expect(page.locator('[data-work-tool="conversation"]')).toHaveAttribute('aria-pressed', 'true')
    expect(await tools.evaluateAll(nodes => nodes.map(node => node.getAttribute('data-work-tool')))).toEqual(['conversation', 'details', 'changes', 'activity', 'browser'])
    await page.keyboard.press('Meta+g')
    await expect(main).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Conversation mode', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await page.keyboard.press('Meta+g')
    await expect(main.locator('.cm-content')).toContainText('retryPayment')
    await expect(main.locator('[data-slot="file-tab-unsaved"]')).toHaveCount(1)
    expect(errors).toEqual([])
  })

  test(`Explorer preview tabs, dirty close and file views in ${theme}`, async ({ page }) => {
    await openFrame(page, 'frame-wall=conversation&frame-editor-mode=source', theme)
    const main = page.locator('[data-slot="editor-main"]'), left = page.locator('[data-left-column]:visible')
    await left.getByRole('radio', { name: 'All', exact: true }).click()
    await left.getByRole('button', { name: 'unchanged.ts', exact: true }).click()
    await expect(main.getByRole('tab', { name: 'README.md', exact: true })).toHaveCount(0)
    const preview = main.getByRole('tab', { name: 'unchanged.ts', exact: true })
    await expect(preview).toBeVisible()
    expect(await preview.evaluate(node => getComputedStyle(node).fontStyle)).toBe('italic')
    await expect(main.getByRole('radio', { name: /^Changes/ })).toHaveCount(0)
    await left.getByRole('button', { name: 'unchanged.ts', exact: true }).dblclick()
    await expect.poll(() => preview.evaluate(node => getComputedStyle(node).fontStyle)).toBe('normal')
    await left.getByRole('button', { name: 'README.md', exact: true }).click()
    await expect(main.getByRole('tab')).toHaveCount(3)
    await expect(main.getByRole('radio', { name: 'Preview', exact: true })).toBeChecked()
    await expect(main.getByRole('radio', { name: /^Changes/ })).toBeVisible()
    await main.getByRole('button', { name: 'Edit', exact: true }).click()
    await expect(main.getByRole('radio', { name: 'Source', exact: true })).toBeChecked()
    await main.getByRole('radio', { name: /^Changes/ }).click()
    await expect(main.locator('.cm-insertedLine').first()).toBeVisible()
    await main.getByRole('tab', { name: 'auth.ts, unsaved', exact: true }).click()
    await main.getByRole('button', { name: 'Close auth.ts', exact: true }).click()
    const dialog = page.getByRole('alertdialog')
    await expect(dialog.getByRole('button', { name: 'Save', exact: true })).toBeVisible()
    await expect(dialog.getByRole('button', { name: "Don't save", exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(main.getByRole('tab', { name: 'auth.ts, unsaved', exact: true })).toBeVisible()
    await main.getByRole('button', { name: 'Close auth.ts', exact: true }).click()
    await dialog.getByRole('button', { name: "Don't save", exact: true }).click()
    await expect(main.getByRole('tab', { name: 'auth.ts, unsaved', exact: true })).toHaveCount(0)
  })

  test(`Ask inserts a quote without sending, and Review and Pop out enter Editor in ${theme}`, async ({ page }) => {
    await openFrame(page, 'frame-wall=conversation&frame-editor-mode=ask', theme)
    const main = page.locator('[data-slot="editor-main"]'), right = page.locator('[data-frame-region="right"]')
    const composer = right.locator('textarea'), action = page.getByRole('button', { name: 'Ask in chat ⌘L', exact: true })
    await expect(action).toBeVisible()
    const transcript = await right.locator('[data-live-transcript]').textContent()
    await action.click()
    await expect(composer).toHaveValue(/src\/auth\.ts:3[\s\S]*retryPayment/)
    await expect(composer).toBeFocused()
    await expect(right.locator('[data-live-transcript]')).toHaveText(transcript ?? '')
    await page.getByRole('button', { name: 'Conversation mode', exact: true }).click()
    await page.getByRole('button', { name: 'Review', exact: true }).click()
    await expect(main.getByRole('radio', { name: /^Changes/ })).toBeChecked()
    await expect(page.getByRole('radio', { name: 'Changed 4', exact: true })).toBeChecked()
    await page.getByRole('button', { name: 'Conversation mode', exact: true }).click()
    await page.getByTitle('Open README.md', { exact: true }).click()
    await expect(right.getByRole('radio', { name: 'Preview', exact: true })).toBeChecked()
    await right.getByRole('button', { name: 'Edit', exact: true }).click()
    await right.locator('.cm-content').focus()
    await page.keyboard.press('Meta+End'); await page.keyboard.insertText('\nPanel note.\n')
    await right.getByRole('button', { name: 'Pop out to Editor mode', exact: true }).click()
    await expect(main.locator('.cm-content')).toContainText('Panel note.')
    await expect(main.getByRole('tab', { name: 'README.md, unsaved', exact: true })).toBeVisible()
  })

  test(`switch is absent in Settings and disabled on a Team in ${theme}`, async ({ page }) => {
    await openFrame(page, 'frame-wall=settings&frame-section=appearance', theme)
    await expect(page.locator('[data-left-top] [data-mode-switch]')).toHaveCount(0)
    await page.getByRole('switch', { name: 'Minimap', exact: true }).scrollIntoViewIfNeeded()
    await expect(page.getByRole('switch', { name: 'Minimap', exact: true })).toBeVisible()
    await openFrame(page, 'frame-wall=team', theme)
    const editor = page.getByRole('button', { name: 'Editor mode', exact: true })
    await expect(editor).toBeDisabled()
    await expect(editor).toHaveAttribute('title', "Editor mode opens a conversation's files")
    await page.keyboard.press('Meta+g')
    await expect(page.locator('[data-slot="editor-main"]')).toHaveCount(0)
  })

  test(`a disk change keeps unsaved bytes until Keep mine is chosen in ${theme}`, async ({ page }) => {
    await openFrame(page, 'frame-wall=conversation&frame-editor-mode=source', theme)
    const main = page.locator('[data-slot="editor-main"]')
    await expect(main.locator('.cm-content')).toContainText('retryPayment')
    await page.evaluate(() => (window as Window & { __hdFrameWall: { changeEditorDisk: () => void } }).__hdFrameWall.changeEditorDisk())
    await expect(main.getByText('auth.ts changed on disk while you had unsaved edits.', { exact: true })).toBeVisible()
    await expect(main.locator('.cm-content')).toContainText('retryPayment')
    for (const name of ['Compare', 'Reload', 'Keep mine']) await expect(main.getByRole('button', { name, exact: true })).toBeVisible()
    await main.getByRole('button', { name: 'Keep mine', exact: true }).click()
    await expect(main.getByRole('button', { name: 'Unsaved · Save ⌘S', exact: true })).toHaveCount(0)
    await expect(main.getByText('auth.ts changed on disk while you had unsaved edits.', { exact: true })).toHaveCount(0)
    await expect(main.locator('.cm-content')).toContainText('retryPayment')
  })
  test(`tracked deletion shows removed HEAD lines without creating the file in ${theme}`, async ({ page }, testInfo) => {
    await openFrame(page, 'frame-wall=conversation&frame-editor-mode=deleted', theme)
    const main = page.locator('[data-slot="editor-main"]')
    await expect(main.getByRole('radio', { name: 'Changes +0 −4', exact: true })).toBeChecked()
    await expect(main.locator('.cm-deletedChunk')).toContainText('token.length > 8')
    await expect(main.locator('.cm-content')).toHaveAttribute('contenteditable', 'false')
    await expect(main.getByRole('button', { name: 'Create this file', exact: true })).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath(`editor-deleted-${theme}.png`) })
    await main.getByRole('radio', { name: 'Source', exact: true }).click()
    await expect(main.getByRole('button', { name: 'Create this file', exact: true })).toBeVisible()
  })
  for (const width of [1440, 1100, 720]) {
    test(`clean deletion and deleted-draft Reload stay missing across polls at ${width} in ${theme}`, async ({ page }, testInfo) => {
      await page.clock.install()
      await openFrame(page, 'frame-wall=conversation&frame-editor-mode=source', theme, width)
      await showEditorAtNarrowWidth(page, width)
      const main = page.locator('[data-slot="editor-main"]')
      await main.getByRole('button', { name: 'Unsaved · Save ⌘S', exact: true }).click()
      await expect(main.locator('[data-slot="file-tab-unsaved"]')).toHaveCount(0)
      const remove = () => page.evaluate(() => (window as Window & { __hdFrameWall: { changeEditorDisk: (kind: 'delete') => void } }).__hdFrameWall.changeEditorDisk('delete'))
      await remove()
      await page.clock.fastForward(3100)
      await expect(main.getByRole('button', { name: 'Create this file', exact: true })).toBeVisible()
      await page.clock.fastForward(3100)
      await expect(main.getByRole('button', { name: 'Create this file', exact: true })).toBeVisible()
      await main.getByRole('radio', { name: 'Changes +0 −4', exact: true }).click()
      await expect(main.locator('.cm-deletedChunk')).toContainText('token.length > 8')
      await expect(main.locator('.cm-content')).toHaveAttribute('contenteditable', 'false')
      await page.screenshot({ path: testInfo.outputPath(`editor-clean-deletion-${width}-${theme}.png`) })

      await openFrame(page, 'frame-wall=conversation&frame-editor-mode=source', theme, width)
      await showEditorAtNarrowWidth(page, width)
      await expect(main.locator('.cm-content')).toContainText('retryPayment')
      await remove()
      await page.clock.fastForward(3100)
      await expect(main.getByRole('button', { name: 'Reload', exact: true })).toBeVisible()
      await main.getByRole('button', { name: 'Reload', exact: true }).click()
      await page.clock.fastForward(3100)
      await expect(main.getByRole('button', { name: 'Create this file', exact: true })).toBeVisible()
      await expect(main.locator('[data-slot="file-tab-unsaved"]')).toHaveCount(0)
      await expect(main.locator('.cm-content')).toHaveCount(0)
      await page.screenshot({ path: testInfo.outputPath(`editor-reload-deletion-${width}-${theme}.png`) })
    })
    test(`an admitted alias retains Changed letters and editable HEAD comparison at ${width} in ${theme}`, async ({ page }, testInfo) => {
      await openFrame(page, 'frame-wall=conversation&frame-editor-mode=alias', theme, width)
      const main = page.locator('[data-slot="editor-main"]')
      if (width < 1000) await page.getByRole('button', { name: 'Show sidebar', exact: true }).click()
      await expect(page.getByRole('radio', { name: 'Changed 4', exact: true })).toBeChecked()
      await expect(page.locator('[aria-label="auth.ts: modified"]')).toBeVisible()
      await showEditorAtNarrowWidth(page, width)
      await main.getByRole('radio', { name: /^Changes/ }).click()
      await expect(main.locator('.cm-deletedChunk')).toContainText('token.length > 8')
      await expect(main.locator('.cm-content')).toHaveAttribute('contenteditable', 'true')
      await page.screenshot({ path: testInfo.outputPath(`editor-alias-${width}-${theme}.png`) })
    })
  }
}
