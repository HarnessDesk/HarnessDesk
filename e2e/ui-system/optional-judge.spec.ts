import { expect, test } from '@playwright/test'

for (const theme of ['light', 'dark'] as const) test(`a completed person choice retains both attempt labels in ${theme}`, async ({ page }) => {
  await page.emulateMedia({ colorScheme: theme })
  await page.goto(`/preview.html?comparison-verdict=person-merged&theme=${theme}`)
  const frame = page.locator('[data-frame-id="comparison-person-merged"]')
  // Teams enter Work by default. Choose Chat to inspect the fixture's saved
  // split layout rather than assuming the attempt grid is the landing page.
  await frame.getByRole('tab', { name: 'Chat', exact: true }).click()
  const tiles = frame.locator('[data-slot="side-by-side-tile"]')
  await expect(tiles).toHaveCount(2)
  await expect(tiles.nth(0).locator(':scope > [data-slot="bar"][data-rule="bottom"]')).toContainText('Picked')
  await expect(tiles.nth(1).locator(':scope > [data-slot="bar"][data-rule="bottom"]')).toContainText('Not kept')
  await expect(frame.getByRole('button', { name: 'Pick an attempt…' })).toHaveCount(0)
  const decision = frame.locator('[data-slot="comparison-decision"]')
  await expect(decision).toContainText('You picked A')
  await expect(decision.getByRole('button', { name: /^Merge / })).toHaveCount(0)
  await expect(decision.getByRole('button', { name: 'Refresh merge destination' })).toHaveCount(0)
  await expect(decision.getByRole('button', { name: /^Keep / })).toHaveCount(0)
  await expect(decision.getByRole('button', { name: 'Compare changes' })).toBeEnabled()
})

test('Side by side defaults to You and allows either attempt’s provider to judge', async ({ page }) => {
  await page.goto('/preview.html?team-start=comparison')
  const dialog = page.getByRole('dialog', { name: 'New Team', exact: true })
  const details = dialog.getByRole('button', { name: 'Details', exact: true })
  const configure = page.getByRole('button', { name: 'Configure Judge', exact: true })
  const judge = page.getByRole('button', { name: 'Runtime for Judge', exact: true })
  const row = dialog.locator('[data-flow-details] [data-slot="row"]').filter({ has: page.getByRole('button', { name: 'Configure Judge', exact: true, includeHidden: true }) })
  await expect(row).toHaveCount(1)
  await expect(row).toBeHidden()
  await expect(details).toHaveAttribute('aria-expanded', 'false')
  await details.click()
  await expect(details).toHaveAttribute('aria-expanded', 'true')
  await expect(row.getByText('Optional', { exact: true })).toBeVisible()
  await expect(configure).toHaveText('You')
  await expect(judge).toHaveCount(0)
  await configure.click()
  await expect(judge).toHaveText('You')
  await expect(page.getByRole('button', { name: 'Model for Judge' })).toHaveCount(0)
  await judge.click()
  await page.getByRole('menuitemradio', { name: 'Runtime 1', exact: true }).click()
  await expect(configure).toContainText('Runtime 1')
  // Enabling the Judge moves its control from Details into the graph. Its
  // old popover unmounts; open the current seat's configuration to inspect it.
  await expect(row).toHaveCount(0)
  await expect(judge).toHaveCount(0)
  await configure.click()
  await expect(judge).toHaveText('Runtime 1')
  await expect(page.getByRole('button', { name: 'Model for Judge' })).toBeVisible()
  await judge.click()
  await page.getByRole('menuitemradio', { name: 'You', exact: true }).click()
  await expect(configure).toHaveText('You')
  await expect(row.getByText('Optional', { exact: true })).toBeVisible()
  await expect(judge).toHaveCount(0)
  await configure.click()
  await expect(judge).toHaveText('You')
  await expect(page.getByRole('button', { name: 'Model for Judge' })).toHaveCount(0)
})

test('/race defaults to You and offers both providers as judges', async ({ page }) => {
  await page.goto('/preview.html?optional-judge')
  const dialog = page.getByRole('dialog', { name: 'New Team', exact: true })
  const details = dialog.getByRole('button', { name: 'Details', exact: true })
  const configure = page.getByRole('button', { name: 'Configure Judge', exact: true })
  const judge = page.getByRole('button', { name: 'Runtime for Judge', exact: true })
  await expect(dialog.locator('[data-flow-details]')).toBeHidden()
  await expect(details).toHaveAttribute('aria-expanded', 'false')
  await details.click()
  await expect(details).toHaveAttribute('aria-expanded', 'true')
  await expect(configure).toHaveText('You')
  await expect(judge).toHaveCount(0)
  await configure.click()
  await expect(judge).toHaveText('You')
  await expect(page.getByRole('button', { name: 'Model for Judge' })).toHaveCount(0)
  await judge.click()
  await page.getByRole('menuitemradio', { name: 'Runtime 1', exact: true }).click()
  await expect(configure).toContainText('Runtime 1')
  await expect(judge).toHaveCount(0)
  await configure.click()
  await expect(judge).toHaveText('Runtime 1')
  await expect(page.getByRole('button', { name: 'Model for Judge' })).toBeVisible()
  await judge.click()
  await page.getByRole('menuitemradio', { name: 'Runtime 2', exact: true }).click()
  await expect(judge).toHaveText('Runtime 2')
  await expect(configure).toContainText('Runtime 2')
  await judge.click()
  await page.getByRole('menuitemradio', { name: 'You', exact: true }).click()
  await expect(configure).toHaveText('You')
  await expect(judge).toHaveCount(0)
  await configure.click()
  await expect(judge).toHaveText('You')
  await expect(page.getByRole('button', { name: 'Model for Judge' })).toHaveCount(0)
})
