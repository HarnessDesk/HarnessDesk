import { expect, test } from '@playwright/test'

test.use({ screenshot: 'off', trace: 'off', video: 'off' })
for (const feature of ['phone', 'lead'] as const) test(`${feature} stays discoverable and toggles through synthetic host settings`, async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 480 })
  await page.goto(`/preview.html?frame-wall=settings&frame-section=${feature}&frame-features=off`)
  const label = feature === 'phone' ? 'Mobile' : 'Lead'
  const toggle = page.getByRole('switch', { name: `Enable ${label}`, exact: true })
  await expect(toggle).toBeVisible(); await expect(toggle).not.toBeChecked()
  await toggle.click(); await expect(toggle).toBeChecked()
  if (feature === 'phone') {
    await page.getByRole('button', { name: 'Show code', exact: true }).click()
    await expect(page.getByRole('img', { name: 'Pairing code', exact: true })).toBeVisible()
  }
  await toggle.click(); await expect(toggle).not.toBeChecked()
  await expect(page.getByRole('img', { name: 'Pairing code', exact: true })).toHaveCount(0)
  const nav = page.getByRole('navigation', { name: 'Settings navigation', exact: true })
  await nav.getByRole('button', { name: 'Browser', exact: true }).scrollIntoViewIfNeeded()
  await nav.getByRole('button', { name: 'Browser', exact: true }).click()
  await expect(nav.getByRole('button', { name: 'Back', exact: true })).toBeVisible()
  await expect(nav.getByRole('searchbox', { name: 'Search settings', exact: true })).toBeVisible()
  await nav.getByRole('button', { name: label, exact: true }).click()
  await expect(toggle).not.toBeChecked()
  if (feature === 'phone') {
    await nav.getByRole('button', { name: 'Lead', exact: true }).click()
    await page.getByRole('switch', { name: 'Enable Lead', exact: true }).click()
    await expect(page.getByLabel('Lead identity', { exact: true })).toBeVisible()
    await expect(page.getByText('The Lead could not complete that action.', { exact: true })).toHaveCount(0)
  }
})
test('feature problem fences switches and repair follows its acknowledged off state', async ({ page }) => {
  await page.goto('/preview.html?frame-wall=settings&frame-section=phone&frame-features=problem')
  const toggle = page.getByRole('switch', { name: 'Enable Mobile', exact: true })
  await expect(toggle).toBeDisabled()
  await page.getByRole('button', { name: 'Repair feature settings', exact: true }).click()
  const dialog = page.getByRole('alertdialog')
  await expect(dialog).toContainText('History and phone pairings are retained.')
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  expect(await dialog.evaluate(node => node.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Shift+Tab')
  expect(await dialog.evaluate(node => node.contains(document.activeElement))).toBe(true)
  await dialog.getByRole('button', { name: 'Repair feature settings', exact: true }).click()
  await expect(dialog).toHaveCount(0); await expect(toggle).toBeEnabled(); await expect(toggle).not.toBeChecked()
  await expect(toggle).toBeFocused()
})
test('failed feature save stays inline with the switch off', async ({ page }) => {
  await page.goto('/preview.html?frame-wall=settings&frame-section=phone&frame-features=save-error')
  const toggle = page.getByRole('switch', { name: 'Enable Mobile', exact: true })
  await toggle.click()
  await expect(page.getByRole('alert')).toContainText('Feature settings could not be saved. Try again.')
  await expect(toggle).not.toBeChecked()
})
test('Lead orders setup, behavior and scheduled work before limits while preserving rule deep links', async ({ page }) => {
  await page.goto('/preview.html?frame-wall=settings&frame-section=lead&frame-features=on&frame-focus=rules:talk')
  const rule = page.locator('[data-lead-settings-focus="rules:talk"]')
  await expect(rule).toBeFocused()
  const headings = await page.locator('[data-slot="page"] h2').allTextContents()
  const position = (text: string) => headings.findIndex(heading => heading.includes(text))
  expect(position('Provider key')).toBeLessThan(position('Rules'))
  expect(position('Rules')).toBeLessThan(position('Allowances'))
  expect(position('Memory')).toBeLessThan(position('Allowances'))
  expect(position('Allowances')).toBeLessThan(position('Permissions'))
})
for (const state of ['off', 'problem'] as const) test(`signed-in account access remains editable while local Mobile is ${state}`, async ({ page }) => {
  await page.goto(`/preview.html?desk-account=settings&account-section=mobile&feature-mobile=${state}`)
  const local = page.getByRole('switch', { name: 'Enable Mobile', exact: true })
  const remote = page.getByRole('switch', { name: 'Reachable from your phone', exact: true })
  await expect(remote).toBeChecked()
  await expect(page.getByText('Your saved reachability choice is kept.', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Show code', exact: true })).toHaveCount(0)
  await remote.click(); await expect(remote).not.toBeChecked()
  await page.getByRole('button', { name: 'Unlink', exact: true }).click()
  const dialog = page.getByRole('alertdialog')
  await expect(dialog).toContainText('This phone will lose access to this desk.')
  await dialog.getByRole('button', { name: 'Unlink', exact: true }).click()
  await expect(page.getByText('No phones linked yet.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Show code', exact: true })).toHaveCount(0)
  if (state === 'off') await expect(local).not.toBeChecked()
  else await expect(local).toBeDisabled()
})
